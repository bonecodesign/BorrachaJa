create extension if not exists pgcrypto with schema extensions;

create table public.app_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(trim(display_name)) between 2 and 100),
  created_at timestamptz not null default now()
);

create table public.service_categories (
  id smallint generated by default as identity primary key,
  code text not null unique check (code in ('map_borracharia','borracharia_delivery','reboque_moto')),
  name text not null,
  commission_percent numeric(5,2) not null check (commission_percent in (0,15)),
  paid_in_app boolean not null,
  constraint category_commission_rules check (
    (code = 'map_borracharia' and commission_percent = 0 and paid_in_app = false)
    or (code in ('borracharia_delivery','reboque_moto') and commission_percent = 15 and paid_in_app = true)
  )
);

insert into public.service_categories(code,name,commission_percent,paid_in_app)
values
  ('map_borracharia','Mapa de borracharias',0,false),
  ('borracharia_delivery','Borracharia no local',15,true),
  ('reboque_moto','Reboque de motos',15,true);

create table public.providers (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid unique references auth.users(id) on delete set null,
  display_name text not null check (char_length(trim(display_name)) between 2 and 120),
  description text,
  street_address text,
  city text not null default 'Belo Horizonte',
  state_code char(2) not null default 'MG',
  latitude numeric(9,6),
  longitude numeric(9,6),
  status text not null default 'pending' check (status in ('pending','approved','rejected','suspended')),
  is_active boolean not null default false,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  constraint provider_coords_pair check (
    (latitude is null and longitude is null)
    or (latitude between -90 and 90 and longitude between -180 and 180)
  ),
  constraint provider_approval_consistency check (
    status <> 'approved' or approved_at is not null
  )
);

create index providers_map_idx on public.providers(city,state_code,status,is_active);
create index providers_owner_idx on public.providers(owner_id);

create table public.provider_services (
  provider_id uuid not null references public.providers(id) on delete cascade,
  category_id smallint not null references public.service_categories(id),
  is_active boolean not null default false,
  price_note text,
  created_at timestamptz not null default now(),
  primary key (provider_id,category_id)
);
create index provider_services_category_idx on public.provider_services(category_id,provider_id) where is_active;

create table public.service_requests (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id),
  category_id smallint not null references public.service_categories(id),
  provider_id uuid references public.providers(id),
  latitude numeric(9,6),
  longitude numeric(9,6),
  address_details text,
  problem_description text not null check (char_length(trim(problem_description)) between 5 and 2000),
  status text not null default 'requested' check (
    status in ('requested','quoted','accepted','in_progress','completed','cancelled')
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint request_coords_pair check (
    (latitude is null and longitude is null)
    or (latitude between -90 and 90 and longitude between -180 and 180)
  )
);
create index requests_customer_idx on public.service_requests(customer_id,created_at desc);
create index requests_provider_idx on public.service_requests(provider_id,created_at desc);

create table public.service_quotes (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.service_requests(id) on delete cascade,
  provider_id uuid not null references public.providers(id),
  amount_cents integer not null check(amount_cents > 0),
  details text,
  status text not null default 'proposed' check (status in ('proposed','accepted','declined','expired')),
  created_at timestamptz not null default now()
);
create index quotes_request_idx on public.service_quotes(request_id,created_at desc);

create table public.request_messages (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.service_requests(id) on delete cascade,
  sender_id uuid not null references auth.users(id),
  body text not null check (char_length(trim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index messages_request_idx on public.request_messages(request_id,created_at);

create table public.payment_records (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique references public.service_requests(id),
  gross_amount_cents integer not null check (gross_amount_cents > 0),
  commission_percent numeric(5,2) not null default 15 check (commission_percent = 15),
  platform_fee_cents integer generated always as (round(gross_amount_cents::numeric * 0.15)::integer) stored,
  provider_amount_cents integer generated always as
    (gross_amount_cents - round(gross_amount_cents::numeric * 0.15)::integer) stored,
  status text not null default 'pending' check (
    status in ('pending','authorized','paid','failed','refunded')
  ),
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

-- Protecao por linha: nao expor pedidos, conversas, orcamentos ou valores a terceiros.
alter table public.app_profiles enable row level security;
alter table public.service_categories enable row level security;
alter table public.providers enable row level security;
alter table public.provider_services enable row level security;
alter table public.service_requests enable row level security;
alter table public.service_quotes enable row level security;
alter table public.request_messages enable row level security;
alter table public.payment_records enable row level security;

-- Permissoes minimas: escrita financeira e aprovacao de prestadores so pelo backend.
revoke all on public.app_profiles, public.service_categories, public.providers,
  public.provider_services, public.service_requests, public.service_quotes,
  public.request_messages, public.payment_records from anon, authenticated;
grant select on public.service_categories, public.providers, public.provider_services to anon,authenticated;
grant select,insert,update on public.app_profiles to authenticated;
grant insert on public.providers,public.provider_services to authenticated;
grant select,insert on public.service_requests,public.service_quotes,public.request_messages to authenticated;
grant select on public.payment_records to authenticated;
grant usage, select on all sequences in schema public to authenticated, anon;

create policy "categories_public_read" on public.service_categories
for select to anon,authenticated using (true);

create policy "profiles_self_read" on public.app_profiles
for select to authenticated using (user_id=(select auth.uid()));
create policy "profiles_self_create" on public.app_profiles
for insert to authenticated with check (user_id=(select auth.uid()));
create policy "profiles_self_update" on public.app_profiles
for update to authenticated using (user_id=(select auth.uid()))
with check (user_id=(select auth.uid()));

create policy "providers_public_or_owner_read" on public.providers
for select to anon,authenticated using (
  (status='approved' and is_active=true)
  or (owner_id=(select auth.uid()))
);
create policy "providers_owner_pending_create" on public.providers
for insert to authenticated with check (
  owner_id=(select auth.uid()) and status='pending'
  and is_active=false and approved_at is null
);

create policy "provider_services_public_or_owner_read" on public.provider_services
for select to anon,authenticated using (
  exists (
    select 1 from public.providers p
    where p.id=provider_id and
    ((p.status='approved' and p.is_active=true and is_active=true)
      or p.owner_id=(select auth.uid()))
  )
);
create policy "provider_services_owner_pending_create" on public.provider_services
for insert to authenticated with check (
  is_active=false and exists (
    select 1 from public.providers p
    where p.id=provider_id and p.owner_id=(select auth.uid())
  )
);

create policy "requests_participants_read" on public.service_requests
for select to authenticated using (
  customer_id=(select auth.uid()) or exists(
    select 1 from public.providers p
    where p.id=provider_id and p.owner_id=(select auth.uid())
  )
);
create policy "requests_customer_create" on public.service_requests
for insert to authenticated with check (
  customer_id=(select auth.uid()) and status='requested'
  and exists (
    select 1 from public.service_categories c
    where c.id=category_id and c.paid_in_app=true
  )
  and (
    provider_id is null or exists(
      select 1 from public.provider_services ps
      join public.providers p on p.id=ps.provider_id
      where ps.provider_id=service_requests.provider_id
        and ps.category_id=service_requests.category_id
        and ps.is_active=true and p.status='approved' and p.is_active=true
    )
  )
);

create policy "quotes_participants_read" on public.service_quotes
for select to authenticated using (
  exists (
    select 1 from public.service_requests r
    where r.id=request_id and (
      r.customer_id=(select auth.uid()) or exists(
        select 1 from public.providers p
        where p.id=service_quotes.provider_id and p.owner_id=(select auth.uid())
          and r.provider_id=p.id
      )
    )
  )
);
create policy "quotes_assigned_provider_create" on public.service_quotes
for insert to authenticated with check (
  status='proposed' and exists (
    select 1 from public.service_requests r
    join public.providers p on p.id=service_quotes.provider_id
    where r.id=request_id and r.provider_id=p.id
      and r.status in ('requested','quoted')
      and p.owner_id=(select auth.uid()) and p.status='approved' and p.is_active=true
  )
);

create policy "messages_participants_read" on public.request_messages
for select to authenticated using (
  exists (
    select 1 from public.service_requests r
    where r.id=request_id and (
      r.customer_id=(select auth.uid()) or exists (
        select 1 from public.providers p
        where p.id=r.provider_id and p.owner_id=(select auth.uid())
      )
    )
  )
);
create policy "messages_participants_create" on public.request_messages
for insert to authenticated with check (
  sender_id=(select auth.uid()) and exists (
    select 1 from public.service_requests r
    where r.id=request_id and r.status not in ('completed','cancelled')
      and (
        r.customer_id=(select auth.uid()) or exists (
          select 1 from public.providers p
          where p.id=r.provider_id and p.owner_id=(select auth.uid())
        )
      )
  )
);

create policy "payment_records_participants_read" on public.payment_records
for select to authenticated using (
  exists (
    select 1 from public.service_requests r
    where r.id=request_id and (
      r.customer_id=(select auth.uid()) or exists (
        select 1 from public.providers p
        where p.id=r.provider_id and p.owner_id=(select auth.uid())
      )
    )
  )
);
