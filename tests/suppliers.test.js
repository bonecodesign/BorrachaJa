const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const leads = require('../supplier-import.js');
const csv = fs.readFileSync(path.join(__dirname,'../fornecedores_candidatos_exemplo.csv'),'utf8');
const rows=leads.loadCsv(csv);
assert.equal(rows.length,2);
assert.equal(rows[0].business_name,'Prestador Exemplo A');
assert.equal(rows[0].offers_workshop,false);
assert.equal(rows[0].offers_delivery,true);
assert.equal(rows[0].offers_tow,false);
assert.equal(rows[1].business_name,'Reboque Exemplo B');
assert.equal(rows[1].offers_tow,true);
assert.equal(rows[1].offers_delivery,false);
assert.equal(rows[0].status,'prospect');
assert.ok(rows[0].source_key.startsWith('lead-'));
assert.notEqual(rows[0].source_key,rows[1].source_key);
assert.equal(leads.loadCsv(csv)[0].source_key,rows[0].source_key);
const multi='nome;bairro;cidade;borracharia;delivery;reboque;origem;observacoes;contato_administrativo\r\n"Oficina; do Zé";Centro;Belo Horizonte;sim;sim;nao;Lista;"Atende ""motos""";\r\n';
const parsed=leads.loadCsv(multi);
assert.equal(parsed[0].business_name,'Oficina; do Zé');
assert.equal(parsed[0].notes,'Atende "motos"');
assert.equal(parsed[0].offers_workshop,true);
assert.equal(parsed[0].offers_delivery,true);
assert.throws(()=>leads.loadCsv('nome;borracharia;delivery;reboque\nTeste Loja;nao;nao;nao'),/Marque ao menos uma categoria/);
assert.throws(()=>leads.loadCsv('nome;borracharia;delivery;reboque\nBorracha Um;sim;nao;nao\nBorracha Um;sim;nao;nao'),/duplicados/);
const sql=fs.readFileSync(path.join(__dirname,'../supabase/02_fornecedores_potenciais.sql'),'utf8');
assert.match(sql,/enable row level security/);
assert.match(sql,/revoke all on table public\.bj_supplier_leads from anon, authenticated/);
assert.match(sql,/private\.bj_is_admin\(\)/);
assert.doesNotMatch(sql,/grant\s+select[^\n]*\bto anon\b/i);
const live=fs.readFileSync(path.join(__dirname,'../live-app.js'),'utf8');
assert.match(live,/supplierLeadsPage/);
assert.match(live,/if\(!st\.admin\)return/);
assert.match(live,/ignoreDuplicates:true/);
console.log('OK: CSV, múltiplas categorias, duplicatas, tela admin e salvaguardas de acesso estáticas.');